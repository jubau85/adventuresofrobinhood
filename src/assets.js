export const ART = {};
const artListeners = [];

export function onArt(fn) { artListeners.push(fn); }

// Figurenbögen (3D-Figuren, Held, Pferde) erst laden, wenn eine Figur sie braucht: spart Ladezeit und Speicher
const LAZY = /^(fig3d_|held_|pferd3d_)/;
const requested = new Set();
function loadOne(id) {
  if (requested.has(id) || !ART_FILES[id]) return;
  requested.add(id);
  const im = new Image();
  im.decoding = 'async';
  im.onload = () => { ART[id] = im; for (const f of artListeners) f(id); };
  im.src = ART_FILES[id];
}
export function loadArt() {
  for (const id of Object.keys(ART_FILES)) if (!LAZY.test(id)) loadOne(id);
}
// Bild bei Bedarf anfordern; gibt es schon geladen zurück, sonst null (es kommt später)
export function wantArt(id) {
  const im = ART[id];
  if (im) return im;
  loadOne(id);
  return null;
}
// Alle Bilder mit diesem Anfang anfordern (z. B. alle Bewegungen eines Modells)
export function wantArtPrefix(prefix) {
  if (requested.has('#' + prefix)) return;
  requested.add('#' + prefix);
  for (const id of Object.keys(ART_FILES)) if (id.startsWith(prefix)) loadOne(id);
}
